/**
 * report.mjs — the human artifact.
 *
 * Judges (and teammates) should not have to read a terminal scrollback to
 * know what happened. Every claim in here points at a Kane evidence pack.
 */

import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

/**
 * @param {{
 *  test: string,
 *  url?: string,
 *  ok: boolean,
 *  history: Array<{ attempt: number, action: string, verdict?: any, agentExit?: number, promptFile?: string }>,
 *  bisect?: any
 * }} o
 */
export function writeReport(o) {
  const now = new Date().toISOString();
  const mode = o.mode ?? "test";
  const subject = mode === "objective" ? `objective: ${truncate(o.objective ?? "", 160)}` : `\`${o.test}\``;
  const reproduce =
    mode === "objective"
      ? `kane-cli run "${(o.objective ?? "").replace(/"/g, '\\"')}" --agent --headless --timeout 240`
      : `kane-cli testmd run ${o.test} --agent --headless`;
  const rows = o.history.map((h) => {
    const v = h.verdict;
    const status = !v ? "—" : v.ok ? "PASS" : "FAIL";
    const detail = !v
      ? h.action === "agent"
        ? `agent exit ${h.agentExit ?? "?"}`
        : h.action
      : [
          `exit ${v.exitCode}`,
          v.resultCode != null ? `code ${v.resultCode}` : null,
          v.failingStep ? `step ${v.failingStep.step}` : null,
          v.credits != null ? `${Math.round(v.credits)} cr` : null,
        ]
          .filter(Boolean)
          .join(" · ");
    const evidence = v?.sessionDir ? `\`${v.sessionDir}\`` : "";
    return `| ${h.attempt} | ${h.action} | ${status} | ${detail} | ${evidence} |`;
  });

  const final = [...o.history].reverse().find((h) => h.verdict);

  const md = `# Repro report

Generated ${now}${o.source ? `

_${o.source}_` : ""}

- **Flow:** ${subject}
- **Start URL:** ${o.url ?? "(named in the objective)"}
- **Result:** ${o.ok ? "✅ **closed** — Kane exits 0" : "❌ **not closed**"}
- **Verdict:** ${final?.verdict ? `${final.verdict.status} · exit ${final.verdict.exitCode} · result_code ${final.verdict.resultCode ?? "n/a"}` : "no verdict"}
${final?.verdict?.testUrl ? `- **Test Manager:** ${final.verdict.testUrl}` : ""}
${final?.verdict?.oneLiner ? `\n> ${final.verdict.oneLiner}` : ""}

## The loop

| # | action | verdict | detail | evidence |
|---|---|---|---|---|
${rows.join("\n")}

${
  o.culprit
    ? `## The commit that broke it

\`${o.culprit.sha}\`${o.culprit.files?.length ? ` — ${o.culprit.files.map((f) => `\`${f}\``).join(", ")}` : ""}

The fix prompt carried this diff; the agent was not told what to change by hand.
`
    : ""
}
${
  o.bisect
    ? `## Culprit

${
  o.bisect.culprit
    ? `\`${o.bisect.culprit.sha}\` — ${o.bisect.culprit.subject}
${o.bisect.culprit.files?.length ? `\nFiles: ${o.bisect.culprit.files.map((f) => `\`${f}\``).join(", ")}` : ""}

Found in ${o.bisect.probes.length} probes (\`good ${o.bisect.good}\` → \`bad ${o.bisect.bad}\`).
`
    : "_No culprit identified._"
}
Probe evidence: \`${o.bisect.evidenceDir}\`
`
    : ""
}
## How to reproduce this report

\`\`\`bash
kane-cli whoami && kane-cli balance
kane-cli testmd run ${o.test} --agent --headless
\`\`\`

Every run above sealed an evidence pack (per-step screenshots, annotated action
shots, console and network logs, failure records). Open one with:

\`\`\`bash
kane-cli evidence serve <path-to-pack.evidence>
\`\`\`

_Generated by repro. Kane CLI is the definition of done._
`;

  const out = resolve("repro-report.md");
  writeFileSync(out, md);
  return out;
}

function truncate(s, n) {
  const flat = String(s).replace(/\s+/g, " ").trim();
  return flat.length > n ? flat.slice(0, n - 1) + "…" : flat;
}
